import { Processor, WorkerHost } from '@nestjs/bullmq';
import { Inject } from '@nestjs/common';
import { Job } from 'bullmq';
import { LoggerService } from 'src/core/logger/logger/logger.service';
import { QueueEmailDto } from '../../application/dto/queue-email.dto';
import { EMAIL_REPOSITORY } from '../../domain/repositories/email.repository';
import type { EmailRepository } from '../../domain/repositories/email.repository';
import { PdfGeneratorService } from '../pdf/pdf-generator.service';
import { EmailProviderFactory } from '../providers/email-provider.factory';
import { EMAIL_QUEUE } from './email.queue.constants';
import { EmailTemplateService } from '../templates/email-template.service';

@Processor(EMAIL_QUEUE)
export class EmailProcessor extends WorkerHost {
  private readonly log: LoggerService;

  constructor(
    @Inject(EMAIL_REPOSITORY)
    private readonly repository: EmailRepository,
    private readonly templateService: EmailTemplateService,
    private readonly providerFactory: EmailProviderFactory,
    private readonly pdfGenerator: PdfGeneratorService,
    logger: LoggerService,
  ) {
    super();
    this.log = logger.setContext(EmailProcessor.name);
  }

  async process(job: Job<QueueEmailDto>): Promise<void> {
    const payload = job.data;
    await this.repository.markProcessing(payload.emailId);
    this.log.info('Email job picked by worker', this.logMeta(payload, job));

    try {
      const html = this.templateService.render(
        payload.template,
        payload.templateData,
        payload.locale,
      );
      // Pre-rendered attachments (e.g. the billing receipt PDF, RAKHAL-237) are
      // carried base64 on the job; decode them back to Buffers. `includePdf` still
      // generates the legacy generic placeholder PDF.
      const preRendered = (payload.attachments ?? []).map((a) => ({
        filename: a.filename,
        content: Buffer.from(a.contentBase64, 'base64'),
        contentType: a.contentType ?? 'application/pdf',
      }));
      const generated = payload.includePdf
        ? [
            {
              filename: `${payload.template.toLowerCase()}-${payload.emailId}.pdf`,
              content: await this.pdfGenerator.generateReportPdf({
                title: payload.subject,
                lines: ['Generated by Rakhal Email System'],
              }),
              contentType: 'application/pdf',
            },
          ]
        : [];
      const attachments = [...preRendered, ...generated];

      await this.providerFactory.getProvider().sendEmail({
        to: payload.to,
        subject: payload.subject,
        html,
        attachments: attachments.length ? attachments : undefined,
      });

      await this.repository.markSent(payload.emailId, 'resend');
      this.log.info(
        'Email sent successfully via provider',
        this.logMeta(payload, job),
      );
    } catch (error) {
      const attemptsUsed = job.attemptsMade + 1;
      await this.repository.markFailed(
        payload.emailId,
        (error as Error).message,
        attemptsUsed,
      );
      this.log.error(
        'Email sending failed with error',
        error,
        this.logMeta(payload, job),
      );

      if (attemptsUsed < 5) {
        this.log.warn(
          `Retrying email send attempt #${attemptsUsed}`,
          this.logMeta(payload, job),
        );
      }

      throw error;
    }
  }

  private logMeta(
    payload: QueueEmailDto,
    job: Job<QueueEmailDto>,
  ): Record<string, unknown> {
    return {
      emailId: payload.emailId,
      userId: payload.userId,
      tenantId: payload.tenantId,
      farmId: payload.farmId,
      correlationId: payload.correlationId,
      queueJobId: job.id,
      timestamp: new Date().toISOString(),
    };
  }
}
