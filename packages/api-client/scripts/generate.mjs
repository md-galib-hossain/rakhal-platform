// Generates src/generated/customer-api.d.ts from apps/api/openapi/customer-api.json.
//   node scripts/generate.mjs           write the file
//   node scripts/generate.mjs --check   fail (exit 1) if the committed file is stale (CI drift check)
// The OpenAPI document itself is kept fresh by `pnpm --filter @rakhal/api gen:openapi:check`.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "..", "..", "apps", "api", "openapi", "customer-api.json");
const outPath = join(root, "src", "generated", "customer-api.d.ts");
const check = process.argv.includes("--check");

const banner = [
  "/**",
  " * GENERATED by packages/api-client/scripts/generate.mjs from apps/api/openapi/customer-api.json.",
  " * Do not edit. Regenerate with `pnpm --filter @rakhal/api-client gen`.",
  " */",
  "",
].join("\n");

const spec = JSON.parse(readFileSync(specPath, "utf8"));

// Known backend gaps: a $ref to a schema that apps/api never registered (missing @ApiExtraModels). openapi-typescript
// refuses unresolved refs, so each is replaced by an empty schema (typed `unknown`). Any ref NOT listed here fails the
// run, so a new gap cannot slip in; remove an entry once the backend registers the schema.
const KNOWN_UNRESOLVED = new Set(["#/components/schemas/HealthGridCellDto"]);

function resolves(ref) {
  let cur = spec;
  for (const part of ref.slice(2).split("/")) cur = cur?.[part];
  return cur !== undefined;
}
const unexpected = [];
function patch(node) {
  if (Array.isArray(node)) return node.forEach(patch);
  if (!node || typeof node !== "object") return;
  if (typeof node.$ref === "string" && !resolves(node.$ref)) {
    if (!KNOWN_UNRESOLVED.has(node.$ref)) unexpected.push(node.$ref);
    delete node.$ref;
    node.description = (node.description ?? "") + " [unresolved in OpenAPI: typed unknown]";
    return;
  }
  Object.values(node).forEach(patch);
}
patch(spec);
if (unexpected.length) {
  console.error(["api-client: unresolved OpenAPI $ref not in KNOWN_UNRESOLVED:", ...new Set(unexpected)].join("\n  "));
  process.exit(1);
}

const ast = await openapiTS(spec, { alphabetize: true });
const next = banner + astToString(ast).replace(/\r\n/g, "\n");

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== next) {
    console.error("api-client drift: src/generated/customer-api.d.ts is stale. Run `pnpm --filter @rakhal/api-client gen` and commit.");
    process.exit(1);
  }
  console.log("api-client: generated types up to date");
} else {
  writeFileSync(outPath, next);
  console.log(`api-client: wrote ${outPath}`);
}
